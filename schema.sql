CREATE TABLE Users (
    User_ID SERIAL PRIMARY KEY,
    Username VARCHAR(50) NOT NULL UNIQUE,
    Email VARCHAR(255) NOT NULL UNIQUE,
    Password_Hash VARCHAR(255) NOT NULL
);

CREATE TABLE Admin (
    Admin_ID SERIAL PRIMARY KEY,
    Username VARCHAR(50) NOT NULL UNIQUE,
    Email VARCHAR(255) NOT NULL UNIQUE,
    Password_Hash VARCHAR(255) NOT NULL
);

CREATE TABLE News (
    News_ID SERIAL PRIMARY KEY,
    News_category VARCHAR(50) NOT NULL,
    Date TIMESTAMP NOT NULL,
    Title VARCHAR(255) NOT NULL,
    Source VARCHAR(100) NOT NULL,
    Author VARCHAR(100) NOT NULL,
    Content TEXT NOT NULL
);

CREATE TABLE Seen_News (
    Seen_News_ID SERIAL PRIMARY KEY,
    User_ID INTEGER NOT NULL REFERENCES Users(User_ID) ON DELETE CASCADE,
    News_ID INTEGER NOT NULL REFERENCES News(News_ID) ON DELETE CASCADE,
    Date TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    Rating INTEGER CHECK (Rating BETWEEN 1 AND 10),
    Commentary TEXT,
    UNIQUE (User_ID, News_ID)
);

CREATE TABLE Muted_Authors (
    Mute_ID SERIAL PRIMARY KEY,
    User_ID INTEGER NOT NULL REFERENCES Users(User_ID) ON DELETE CASCADE,
    Author VARCHAR(100) NOT NULL,
    Mute_Type VARCHAR(10) NOT NULL CHECK (Mute_Type IN ('mute', 'block')),
    Date_Muted TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (User_ID, Author)
);